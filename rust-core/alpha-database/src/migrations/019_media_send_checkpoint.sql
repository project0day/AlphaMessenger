-- T4: контрольная точка отправки — какие куски УЖЕ приняты хранилищем.
--
-- Зачем. До сих пор обрыв связи стоил всего файла целиком: приложение начинало
-- загрузку с нулевого байта, потому что памяти о принятых кусках не было нигде.
-- Замер на устройстве: ролик 53 МБ, связь выключена на 130-м куске из 203 —
-- после возврата ушло 368 кусков вместо 203, то есть 43 МБ впустую.
--
-- Почему здесь, а не в отдельном файле-журнале. Строка на кусок с личностью
-- «отправка + элемент + ревизия + номер куска» уже существует (018) и уже
-- содержит ожидаемую идентичность объекта. Заводить рядом второе хранилище с
-- собственным разбором и собственной устойчивостью к падению значило бы
-- удваивать механизм: атомарность транзакции здесь дана даром, а обрыв записи
-- на половине строки в самодельном файле пришлось бы предусматривать руками.
--
-- ГЛАВНОЕ РАЗЛИЧИЕ, ради которого миграция и написана:
--
--   запись СУЩЕСТВУЕТ  = кусок зарегистрирован (мы собираемся его отправить);
--   confirmed_at ЗАПОЛНЕН = хранилище подтвердило приём ИМЕННО этих байтов.
--
-- Пропускать отправку можно только по второму. Успешный запрос сам по себе
-- ничего не доказывает: подтверждением считается совпадение идентичности,
-- вернувшейся от сервера, с вычисленной нами, и только после того, как
-- транзакция закрыта. Байты, подтверждённые сервером, но не дошедшие до диска,
-- после падения исчезнут — и показывать их как сохранённый прогресс нельзя.
--
-- Остальные поля — это ровно то, чего не хватает, чтобы собрать итоговую ссылку
-- на медиа БЕЗ повторной отправки пропущенных кусков. Получатель не должен по
-- полноте данных отличать возобновлённую отправку от обычной.
--
-- Чего здесь НЕТ и не будет: ключей, шифротекста и исходных байтов. Только
-- идентичности, размеры и адреса — то, что и так уходит в открытую ссылку.

ALTER TABLE media_send_objects ADD COLUMN confirmed_at INTEGER;
ALTER TABLE media_send_objects ADD COLUMN plaintext_bytes INTEGER;
ALTER TABLE media_send_objects ADD COLUMN ciphertext_bytes INTEGER;
ALTER TABLE media_send_objects ADD COLUMN chunk_hash TEXT;
ALTER TABLE media_send_objects ADD COLUMN locations_json TEXT;

-- Возобновление читает куски одной отправки по порядку и только подтверждённые.
CREATE INDEX IF NOT EXISTS idx_media_send_objects_confirmed
    ON media_send_objects(send_id, item_index, revision, object_index)
    WHERE confirmed_at IS NOT NULL;
