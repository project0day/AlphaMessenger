-- T3: ключи шифрования медиа для незавершённой отправки и фоновой репликации.
--
-- Ключ нужен, чтобы ПОСЛЕ смерти процесса заново получить БАЙТ В БАЙТ тот же
-- зашифрованный объект из неизменного исходника: иначе догрузка недостающих
-- реплик невозможна — у копии был бы другой идентификатор, и найти её по
-- содержимому стало бы нельзя.
--
-- Отдельного шифрования у строки нет намеренно: вся база открывается SQLCipher
-- под MasterDataKey, поэтому запись уже зашифрована на диске, доступна только
-- после разблокировки и исчезает вместе с экстренным стиранием. Своё шифрование
-- поверх было бы слабее и появилось бы вторым местом хранения секрета.
--
-- identity собирается ВНУТРИ ядра из (send_id, item_index, revision) — Kotlin
-- произвольную строку сюда передать не может.
CREATE TABLE IF NOT EXISTS media_send_keys (
    identity    TEXT PRIMARY KEY NOT NULL,
    key_material BLOB NOT NULL,
    created_at  INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_media_send_keys_created
    ON media_send_keys(created_at);
