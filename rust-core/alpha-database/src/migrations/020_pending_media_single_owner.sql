-- Одна строка очереди на одно сообщение — и один владелец отправки в каждый
-- момент времени.
--
-- Наблюдалось на устройстве: файл ушёл получателю ДВАЖДЫ. 150 кусков залиты и
-- опубликованы, а через 25 секунд те же 150 кусков залиты заново и сообщение
-- опубликовано второй раз.
--
-- Причин было две, и обе здесь:
--
--   1. msg_id не был уникален, а постановка в очередь делалась простой
--      вставкой. Каждая неудача добавляла ЕЩЁ ОДНУ строку того же сообщения.
--      Успех удаляет строки по msg_id, но обход очереди работает по снимку
--      списка, взятому в начале прохода, и об удалении не знает: вторая запись
--      уходила в отправку уже после того, как сообщение было опубликовано.
--
--   2. Состояние 'uploading' объявлено в схеме с самого начала (миграция 014),
--      но не выставлялось никогда. Взять строку в работу означало просто начать
--      работу — заявить на неё право было нечем.
--
-- Дедупликация ниже оставляет самую раннюю строку каждого сообщения: она несёт
-- исходную попытку и её счётчики. Более поздние — то самое размножение.

DELETE FROM pending_media
WHERE id NOT IN (SELECT MIN(id) FROM pending_media GROUP BY msg_id);

CREATE UNIQUE INDEX IF NOT EXISTS idx_pending_media_msg_unique
    ON pending_media(msg_id);

-- Срок аренды: захват, переживший гибель процесса, обязан истечь, иначе
-- отправка осталась бы навсегда за владельцем, которого больше нет.
ALTER TABLE pending_media ADD COLUMN claimed_at INTEGER;

-- Строки, застрявшие в 'uploading' от прежних запусков, владельца не имеют:
-- до этой миграции это состояние не выставлял никто, а значит и освобождать
-- его некому.
UPDATE pending_media SET status = 'queued', claimed_at = NULL
WHERE status = 'uploading';
