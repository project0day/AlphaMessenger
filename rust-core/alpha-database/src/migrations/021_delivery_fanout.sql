-- ════════════════════════════════════════════════════════════════════════
--  P1 · Состояние доставки ПО КАЖДОМУ получателю
-- ════════════════════════════════════════════════════════════════════════
--
-- Пока прикладные сообщения уходили одним публичным событием, состояние
-- отправки было одно на сообщение: `delivery_outbox.state`. С персональными
-- конвертами NIP-59 у одного логического сообщения появляется N независимых
-- отправок, и одного поля перестаёт хватать:
--
--     группа A, B, C → A принят, B не принят, C принят
--     delivery_outbox.state = 'pending'   ← кому именно не ушло, не записано
--
-- Повтор без этого знания либо шлёт всем заново (A и C получают дубликат),
-- либо не шлёт никому. Здесь и хранится недостающее измерение.
--
-- Это НЕ вторая очередь. Владелец логического сообщения по-прежнему один —
-- `delivery_outbox`; таблица ниже описывает его отправки, а не заменяет его.
--
-- Получатель обозначается КЛЮЧОМ ПОДПИСИ MLS, как и везде в слое доставки
-- (`delivery_acks.acker_id`). Транспортный адрес выводится из проверенного
-- справочника в момент отправки и здесь не хранится: адрес может смениться,
-- участник — нет.

CREATE TABLE IF NOT EXISTS delivery_fanout (
    chat_id          TEXT NOT NULL,
    msg_id           TEXT NOT NULL,
    -- Ключ подписи MLS получателя, шестнадцатеричный.
    recipient_sig    TEXT NOT NULL,

    -- Состояние ОТПРАВКИ, не прочтения:
    --   pending          — снимок создан, попыток ещё не было
    --   in_flight        — конверт отправляется прямо сейчас
    --   relay_accepted   — реле приняло конверт
    --   retry_wait       — временная неудача, ждём следующей попытки
    --   permanent_failed — невосстановимая ошибка
    --   canceled_removed — участник исключён из группы; отправка прекращена
    --
    -- `canceled_removed` заведено отдельно намеренно. Выдать исключённого за
    -- принятого было бы ложью: он ничего не получил. Но и держать сообщение
    -- незавершённым из-за него нельзя — он больше не обязательный получатель.
    -- Честная причина лучше удобного притворства.
    --
    -- `relay_accepted` НЕ означает, что адресат получил и разобрал сообщение.
    -- Подтверждение адресатом живёт отдельно, в `delivery_acks`, и смешивать
    -- их нельзя: реле принимает конверт, ничего не зная о том, дойдёт ли он.
    state            TEXT NOT NULL DEFAULT 'pending'
                     CHECK(state IN ('pending','in_flight','relay_accepted',
                                     'retry_wait','permanent_failed',
                                     'canceled_removed')),

    attempts         INTEGER NOT NULL DEFAULT 0,
    -- Класс последней ошибки (offline/timeout/rate/...), без текста и адресов.
    last_error_class TEXT NOT NULL DEFAULT '',
    last_attempt_at  TEXT NOT NULL DEFAULT '',
    -- Когда реле приняло конверт. Пусто, пока не принято.
    delivered_at     TEXT NOT NULL DEFAULT '',

    PRIMARY KEY (chat_id, msg_id, recipient_sig)
);

-- Выборка работы: что осталось доотправить.
CREATE INDEX IF NOT EXISTS idx_delivery_fanout_state
    ON delivery_fanout(state, last_attempt_at);

-- Все получатели одного сообщения — для сводного состояния.
CREATE INDEX IF NOT EXISTS idx_delivery_fanout_msg
    ON delivery_fanout(chat_id, msg_id);

-- Гибель процесса не должна оставлять вечно «отправляющиеся» строки: они
-- пережили того, кто их отправлял. При открытии базы такие возвращаются в
-- работу — повторная публикация безопасна, потому что получатель отбрасывает
-- повтор логического сообщения по его собственному идентификатору.
UPDATE delivery_fanout SET state = 'pending' WHERE state = 'in_flight';
